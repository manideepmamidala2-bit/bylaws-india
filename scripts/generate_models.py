#!/usr/bin/env python3
"""Single-source code generator for Pydantic v2 models and TypeScript interfaces.

Reads `schemas/*.schema.json` (Schema v1.1) and deterministically writes:
1. `pipeline/bylaws/models/_generated.py` (via `datamodel-code-generator`)
2. `lib/types/generated.ts` (via `json-schema-to-typescript`)
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]

try:
    from datamodel_code_generator import (
        DataModelType,
        Formatter,
        InputFileType,
        PythonVersion,
        generate,
    )
except ModuleNotFoundError:
    completed = subprocess.run(
        [
            "uv",
            "run",
            "--directory",
            str(REPO_ROOT / "pipeline"),
            "python",
            str(Path(__file__).resolve()),
            *sys.argv[1:],
        ],
        check=False,
    )
    raise SystemExit(completed.returncode) from None

SCHEMAS_DIR = REPO_ROOT / "schemas"
PY_OUTPUT = REPO_ROOT / "pipeline" / "bylaws" / "models" / "_generated.py"
TS_OUTPUT = REPO_ROOT / "lib" / "types" / "generated.ts"

SCHEMA_FILES: tuple[str, ...] = (
    "jurisdiction.schema.json",
    "document.schema.json",
    "clause-tree.schema.json",
    "annotations.schema.json",
    "zones.schema.json",
    "overrides.schema.json",
    "declarations.schema.json",
    "amendments.schema.json",
    "manifest.schema.json",
    "consolidated.schema.json",
    "geo-layers.schema.json",
    "clause-zone-tags.schema.json",
    "relations.schema.json",
    "parameters.schema.json",
    "resolution.schema.json",
)


def _rewrite_refs(node: Any, def_prefix: str = "#/$defs/") -> Any:
    """Recursively rewrite local `#/$defs/X` references when merging schemas."""
    if isinstance(node, dict):
        rewritten: dict[str, Any] = {}
        for key, val in node.items():
            if key == "$ref" and isinstance(val, str) and val.startswith("#/$defs/"):
                rewritten[key] = f"{def_prefix}{val.removeprefix('#/$defs/')}"
            else:
                rewritten[key] = _rewrite_refs(val, def_prefix)
        return rewritten
    if isinstance(node, list):
        return [_rewrite_refs(item, def_prefix) for item in node]
    return node


def build_combined_schema() -> dict[str, Any]:
    """Merge all 8 JSON Schemas into a single Draft 2020-12 bundle for unified codegen."""
    combined_defs: dict[str, Any] = {}
    root_refs: list[dict[str, str]] = []

    for filename in SCHEMA_FILES:
        schema_path = SCHEMAS_DIR / filename
        raw: dict[str, Any] = json.loads(schema_path.read_text(encoding="utf-8"))
        title = raw["title"]

        # Copy $defs first
        for def_name, def_schema in raw.get("$defs", {}).items():
            combined_defs[def_name] = _rewrite_refs(def_schema)

        # Register the top-level schema object under its title in $defs
        root_schema = {
            k: _rewrite_refs(v)
            for k, v in raw.items()
            if k not in {"$schema", "$id", "$defs"}
        }
        combined_defs[title] = root_schema
        root_refs.append({"$ref": f"#/$defs/{title}"})

    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://bylaws-india.local/schemas/bundle.schema.json",
        "title": "BylawsSchemaBundle",
        "anyOf": root_refs,
        "$defs": combined_defs,
    }


def generate_python_models(bundle: dict[str, Any]) -> None:
    """Generate `pipeline/bylaws/models/_generated.py` using `datamodel-code-generator`."""
    PY_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp_dir:
        bundle_path = Path(tmp_dir) / "bundle.schema.json"
        out_path = Path(tmp_dir) / "_generated.py"
        bundle_path.write_text(json.dumps(bundle, indent=2), encoding="utf-8")

        generate(
            input_=bundle_path,
            input_file_type=InputFileType.JsonSchema,
            output=out_path,
            output_model_type=DataModelType.PydanticV2BaseModel,
            target_python_version=PythonVersion.PY_312,
            disable_timestamp=True,
            use_standard_collections=True,
            use_union_operator=True,
            use_title_as_name=True,
            collapse_root_models=True,
            enum_field_as_literal="all",
            formatters=[Formatter.RUFF_CHECK, Formatter.RUFF_FORMAT],
        )

        content = out_path.read_text(encoding="utf-8")
        header = (
            '"""AUTO-GENERATED from schemas/*.schema.json via scripts/generate_models.py.\n\n'
            "Do not edit this file by hand; run `make generate` or `npm run generate`.\n"
            '"""\n\n'
        )
        lines = [
            line
            for line in content.splitlines()
            if not line.startswith("# generated by datamodel-codegen:")
            and not line.startswith("#   filename:")
        ]
        PY_OUTPUT.write_text(header + "\n".join(lines).lstrip() + "\n", encoding="utf-8")

    subprocess.run(
        ["uv", "run", "ruff", "check", "--fix", str(PY_OUTPUT)],
        cwd=REPO_ROOT / "pipeline",
        check=True,
    )
    subprocess.run(
        ["uv", "run", "ruff", "format", str(PY_OUTPUT)],
        cwd=REPO_ROOT / "pipeline",
        check=True,
    )


def generate_typescript_types() -> None:
    """Generate `lib/types/generated.ts` using `json-schema-to-typescript`."""
    TS_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    node_script = f"""
const fs = require("fs");
const path = require("path");
const {{ compile }} = require("json-schema-to-typescript");

const schemasDir = {json.dumps(str(SCHEMAS_DIR))};
const outPath = {json.dumps(str(TS_OUTPUT))};
const files = {json.dumps(list(SCHEMA_FILES))};

(async () => {{
  const chunks = [
    "/**",
    " * AUTO-GENERATED from schemas/*.schema.json via scripts/generate_models.py.",
    " * Do not edit this file by hand; run `make generate` or `npm run generate`.",
    " */",
    ""
  ];
  const seenBlocks = new Set();

  for (const file of files) {{
    const fullPath = path.join(schemasDir, file);
    const schema = JSON.parse(fs.readFileSync(fullPath, "utf8"));
    const ts = await compile(schema, schema.title, {{
      bannerComment: "",
      additionalProperties: false,
      style: {{
        semi: true,
        singleQuote: false,
      }},
    }});
    const blocks = ts
      .trim()
      .split(/(?=^export (?:interface|type) )/m)
      .map((b) => b.trim())
      .filter(Boolean);
    for (const block of blocks) {{
      const match = block.match(/^export (?:interface|type) ([A-Za-z0-9_]+)/);
      const name = match ? match[1] : block;
      if (!seenBlocks.has(name)) {{
        seenBlocks.add(name);
        chunks.push(block);
        chunks.push("");
      }}
    }}
  }}

  fs.writeFileSync(outPath, chunks.join("\\n"), "utf8");
}})();
"""
    subprocess.run(
        ["node", "-e", node_script],
        cwd=REPO_ROOT,
        check=True,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify that generated Python and TypeScript files match schemas without drift.",
    )
    args = parser.parse_args()

    before_py = PY_OUTPUT.read_text(encoding="utf-8") if PY_OUTPUT.is_file() else None
    before_ts = TS_OUTPUT.read_text(encoding="utf-8") if TS_OUTPUT.is_file() else None

    bundle = build_combined_schema()
    generate_python_models(bundle)
    generate_typescript_types()

    if args.check:
        after_py = PY_OUTPUT.read_text(encoding="utf-8")
        after_ts = TS_OUTPUT.read_text(encoding="utf-8")
        if before_py != after_py or before_ts != after_ts:
            print(
                "Error: generated model files were out of date with schemas/*.schema.json.",
                file=sys.stderr,
            )
            raise SystemExit(1)
        print("Codegen check passed: _generated.py and generated.ts are up to date.")


if __name__ == "__main__":
    main()
